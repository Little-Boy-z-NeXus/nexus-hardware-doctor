"""PlatformIO pre-build step: compile the selected NeXus JSON profile into C++ constants."""

from __future__ import annotations

import json
from hashlib import sha256
from pathlib import Path

Import("env")  # type: ignore[name-defined]  # PlatformIO/SCons injects this symbol.


def cpp_string(value: object) -> str:
    return json.dumps(str(value), ensure_ascii=True)


def number(value: object) -> str:
    rendered = format(float(value), ".12g")
    return rendered if "." in rendered else f"{rendered}.0"


project_dir = Path(env["PROJECT_DIR"]).resolve()  # type: ignore[name-defined]
configured_path = env.GetProjectOption("custom_nexus_hardware_profile")  # type: ignore[name-defined]
profile_path = (project_dir / configured_path).resolve()
profile = json.loads(profile_path.read_text(encoding="utf-8"))
canonical_profile = json.dumps(
    profile,
    ensure_ascii=False,
    sort_keys=True,
    separators=(",", ":"),
).encode("utf-8")
profile_sha256 = sha256(canonical_profile).hexdigest()

required = {
    "schema_version", "profile_id", "hardware_model_id", "controller",
    "transport", "roles", "components", "safety", "firmware",
}
missing = required - profile.keys()
if missing:
    raise ValueError(f"NeXus hardware profile is missing: {', '.join(sorted(missing))}")

firmware = profile["firmware"]
pins = firmware["pins"]
sensor = firmware["sensor"]
identity = sensor["identity"]
imu = firmware.get("imu")
safety = profile["safety"]
baud_rate = profile["transport"].get("baud_rate", 115200)
components = {item["component_id"]: item for item in profile["components"]}
sensor_component = components[profile["roles"]["power_monitor"]]
driver_component = components[profile["roles"]["motor_driver"]]
motor_component = components[profile["roles"]["actuator"]]

pin_id = lambda value: cpp_string(f"gpio_{value}")
content = f"""// Generated from {profile_path.name}. Do not edit this file by hand.
#pragma once

#define NEXUS_HARDWARE_PROFILE_SCHEMA_VERSION {cpp_string(profile['schema_version'])}
#define NEXUS_HARDWARE_PROFILE_ID {cpp_string(profile['profile_id'])}
#define NEXUS_HARDWARE_PROFILE_SHA256 {cpp_string(profile_sha256)}
#define NEXUS_HARDWARE_PROFILE_VERSION {cpp_string(firmware['profile_version'])}
#define NEXUS_HARDWARE_MODEL_ID {cpp_string(profile['hardware_model_id'])}
#define NEXUS_CONTROLLER_MODEL {cpp_string(profile['controller']['model'])}
#define NEXUS_CONTROLLER_BOARD_ID {cpp_string(profile['controller']['board_id'])}
#define NEXUS_CONTROLLER_COMPONENT_ID {cpp_string(profile['roles']['controller'])}
#define NEXUS_SENSOR_COMPONENT_ID {cpp_string(profile['roles']['power_monitor'])}
#define NEXUS_SENSOR_MODEL {cpp_string(sensor_component['model'])}
#define NEXUS_DRIVER_COMPONENT_ID {cpp_string(profile['roles']['motor_driver'])}
#define NEXUS_DRIVER_MODEL {cpp_string(driver_component['model'])}
#define NEXUS_MOTOR_COMPONENT_ID {cpp_string(profile['roles']['actuator'])}
#define NEXUS_MOTOR_MODEL {cpp_string(motor_component['model'])}
#define NEXUS_SENSOR_PROFILE {cpp_string(firmware['sensor_profile'])}
#define NEXUS_DRIVER_PROFILE {cpp_string(firmware['driver_profile'])}
#define NEXUS_SERIAL_BAUD_RATE {int(baud_rate)}

#define NEXUS_I2C_SDA_PIN {int(pins['i2c_sda'])}
#define NEXUS_I2C_SCL_PIN {int(pins['i2c_scl'])}
#define NEXUS_MOTOR_ENABLE_PIN {int(pins['motor_enable'])}
#define NEXUS_MOTOR_IN1_PIN {int(pins['motor_in1'])}
#define NEXUS_MOTOR_IN2_PIN {int(pins['motor_in2'])}
#define NEXUS_ENCODER_A_PIN {int(pins['encoder_a'])}
#define NEXUS_ENCODER_B_PIN {int(pins['encoder_b'])}
#define NEXUS_MOTOR_ENABLE_PIN_ID {pin_id(pins['motor_enable'])}
#define NEXUS_MOTOR_IN1_PIN_ID {pin_id(pins['motor_in1'])}
#define NEXUS_MOTOR_IN2_PIN_ID {pin_id(pins['motor_in2'])}
#define NEXUS_ENCODER_A_PIN_ID {pin_id(pins['encoder_a'])}
#define NEXUS_ENCODER_B_PIN_ID {pin_id(pins['encoder_b'])}
#define NEXUS_I2C_SDA_PIN_ID {pin_id(pins['i2c_sda'])}
#define NEXUS_I2C_SCL_PIN_ID {pin_id(pins['i2c_scl'])}

#define NEXUS_SENSOR_I2C_ADDRESS {int(sensor['i2c_address'], 16)}
#define NEXUS_SENSOR_SHUNT_OHMS {number(sensor['shunt_ohms'])}f
#define NEXUS_SENSOR_CURRENT_LSB_MA {number(sensor['current_lsb_ma'])}f
#define NEXUS_SENSOR_MANUFACTURER_ID {int(identity['manufacturer_id'], 16)}
#define NEXUS_SENSOR_DIE_ID {int(identity['die_id'], 16)}
#define NEXUS_SENSOR_DIE_ID_MASK {int(identity['die_id_mask'], 16)}

#define NEXUS_MIN_BUS_VOLTAGE_MV {round(float(safety['min_bus_voltage_v']) * 1000)}
#define NEXUS_MAX_BUS_VOLTAGE_MV {round(float(safety['max_bus_voltage_v']) * 1000)}
#define NEXUS_MAX_CURRENT_MA {number(safety['max_current_ma'])}f
#define NEXUS_MAX_PWM_PERCENT {int(safety['max_pwm_percent'])}
#define NEXUS_DEFAULT_MOTOR_TEST_PWM_PERCENT {int(firmware['default_motor_test_pwm_percent'])}
#define NEXUS_MAX_MOTOR_TEST_DURATION_MS {int(safety['max_motor_test_duration_ms'])}
#define NEXUS_TELEMETRY_INTERVAL_MS {int(profile['telemetry']['interval_ms'])}
"""

control = firmware.get("control")
if control is not None:
    required_three_wheel_pins = {
        "motor_1_enable", "motor_1_in1", "motor_1_in2", "motor_1_encoder_a", "motor_1_encoder_b",
        "motor_2_enable", "motor_2_in1", "motor_2_in2", "motor_2_encoder_a", "motor_2_encoder_b",
        "motor_3_enable", "motor_3_in1", "motor_3_in2", "motor_3_encoder_a", "motor_3_encoder_b",
        "ps2_data", "ps2_cmd", "ps2_att", "ps2_clk",
    }
    missing_three_wheel_pins = required_three_wheel_pins - pins.keys()
    if missing_three_wheel_pins:
        raise ValueError(
            "Three-wheel profile is missing firmware pins: "
            + ", ".join(sorted(missing_three_wheel_pins))
        )

    content += f"""
#define NEXUS_THREE_WHEEL_PS2_PROFILE 1
#define NEXUS_DRIVE_MODE {cpp_string(control['drive_mode'])}
#define NEXUS_ENCODER_COUNTS_PER_OUTPUT_REVOLUTION {number(control['encoder_counts_per_output_revolution'])}f
#define NEXUS_PS2_POLL_INTERVAL_MS {int(control['ps2_poll_interval_ms'])}
#define NEXUS_PS2_FAILSAFE_TIMEOUT_MS {int(control['ps2_failsafe_timeout_ms'])}
#define NEXUS_JOYSTICK_DEADZONE {int(control['joystick_deadzone'])}
#define NEXUS_ARM_CENTERED_PACKETS {int(control.get('arm_centered_packets', 10))}
#define NEXUS_BALANCE_PID_KP {number(control.get('balance_pid_kp', 0.20))}f
#define NEXUS_BALANCE_PID_KI {number(control.get('balance_pid_ki', 0.05))}f
#define NEXUS_BALANCE_PID_KD {number(control.get('balance_pid_kd', 0.0))}f
#define NEXUS_BALANCE_PID_MAX_CORRECTION_PERCENT {int(control.get('balance_pid_max_correction_percent', 18))}

#define NEXUS_MOTOR_1_ENABLE_PIN {int(pins['motor_1_enable'])}
#define NEXUS_MOTOR_1_IN1_PIN {int(pins['motor_1_in1'])}
#define NEXUS_MOTOR_1_IN2_PIN {int(pins['motor_1_in2'])}
#define NEXUS_MOTOR_1_ENCODER_A_PIN {int(pins['motor_1_encoder_a'])}
#define NEXUS_MOTOR_1_ENCODER_B_PIN {int(pins['motor_1_encoder_b'])}
#define NEXUS_MOTOR_2_ENABLE_PIN {int(pins['motor_2_enable'])}
#define NEXUS_MOTOR_2_IN1_PIN {int(pins['motor_2_in1'])}
#define NEXUS_MOTOR_2_IN2_PIN {int(pins['motor_2_in2'])}
#define NEXUS_MOTOR_2_ENCODER_A_PIN {int(pins['motor_2_encoder_a'])}
#define NEXUS_MOTOR_2_ENCODER_B_PIN {int(pins['motor_2_encoder_b'])}
#define NEXUS_MOTOR_3_ENABLE_PIN {int(pins['motor_3_enable'])}
#define NEXUS_MOTOR_3_IN1_PIN {int(pins['motor_3_in1'])}
#define NEXUS_MOTOR_3_IN2_PIN {int(pins['motor_3_in2'])}
#define NEXUS_MOTOR_3_ENCODER_A_PIN {int(pins['motor_3_encoder_a'])}
#define NEXUS_MOTOR_3_ENCODER_B_PIN {int(pins['motor_3_encoder_b'])}

#define NEXUS_PS2_DATA_PIN {int(pins['ps2_data'])}
#define NEXUS_PS2_CMD_PIN {int(pins['ps2_cmd'])}
#define NEXUS_PS2_ATT_PIN {int(pins['ps2_att'])}
#define NEXUS_PS2_CLK_PIN {int(pins['ps2_clk'])}
"""

    if imu is not None:
        content += f"""

#define NEXUS_BNO055_ENABLED 1
#define NEXUS_BNO055_I2C_ADDRESS {int(imu['i2c_address'], 16)}
"""

output = project_dir / "include" / "nexus_hardware_profile.generated.h"
if not output.exists() or output.read_text(encoding="utf-8") != content:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8", newline="\n")
print(f"NEXUS PROFILE: {profile['profile_id']} -> {output.name}")
